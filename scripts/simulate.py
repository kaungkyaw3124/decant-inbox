class CassetteProvider:
    """Answers from tests/sim/cassettes.json by a hash of (model, reasoning, instructions, input). A missing
    answer is fetched from `real` (record mode, within the cost caps) or is an AI timeout."""
    name = "cassette"

    def __init__(self, path: Path = CASSETTE, real: providers.Provider | None = None):
        self.path, self.real = path, real
        self.tapes: dict = json.loads(path.read_text()) if path.exists() else {}
        self.used: set[str] = set()
        self.recorded = 0
        self.spent = 0.0
        self.misses = 0

    @staticmethod
    def key(model: str, reasoning: str, instructions: str, user_input: str) -> str:
        return hashlib.sha256("\x1f".join((model, reasoning, instructions, user_input)).encode()).hexdigest()[:24]

    def understand(self, instructions, schema, user_input, model, reasoning) -> providers.Reply:
        key = self.key(model, reasoning, instructions, user_input)
        self.used.add(key)
        tape = self.tapes.get(key)
        if tape is None:
            if self.real is None or self.spent >= RUN_CAP_USD or _spent_today() + self.spent >= DAY_CAP_USD:
                self.misses += 1
                raise providers.AIError("timeout", "no recorded answer")
            got = self.real.understand(instructions, schema, user_input, model, reasoning)
            self.spent += providers.cost_usd(got.input_tokens, got.cached_tokens, got.output_tokens)
            tape = {"data": got.data, "tokens": [got.input_tokens, got.cached_tokens, got.output_tokens]}
            self.tapes[key] = tape
            self.recorded += 1
        return providers.Reply(tape["data"], *tape["tokens"], 5)

    def read_image(self, *args, **kwargs):
        raise providers.AIError("other", "screenshots are not simulated")

    def save(self) -> None:
        if self.recorded:
            self.path.write_text(json.dumps(self.tapes, ensure_ascii=False, indent=0, sort_keys=True))


def _spent_today() -> float:
    log = EXPORTS / "sim_cost.json"
    try:
        data = json.loads(log.read_text())
    except (OSError, ValueError):
        return 0.0
    return float(data.get(datetime.now(UTC).date().isoformat(), 0.0))


def _add_spent(usd: float) -> None:
    if not usd:
        return
    EXPORTS.mkdir(parents=True, exist_ok=True)
    log = EXPORTS / "sim_cost.json"
    try:
        data = json.loads(log.read_text())
    except (OSError, ValueError):
        data = {}
    day = datetime.now(UTC).date().isoformat()
    data[day] = round(float(data.get(day, 0.0)) + usd, 6)
    log.write_text(json.dumps(data))


