def load_scenarios(only: set[str] | None = None, tag: str | None = None) -> list[dict]:
    found, seen = [], set()
    for path in sorted(SCENARIOS.glob("*.yaml")):
        for sc in yaml.safe_load(path.read_text()) or []:
            if sc["id"] in seen:
                raise ValueError(f"duplicate scenario id {sc['id']} in {path.name}")
            seen.add(sc["id"])
            sc["file"] = path.name
            if (only is None or sc["id"] in only) and (tag is None or tag in sc.get("tags", [])):
                found.append(sc)
    return found


