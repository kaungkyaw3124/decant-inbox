@dataclass
class Turn:
    index: int
    said: list[str]
    expect: dict
    got: str = "none"  # auto | person | none
    replies: list[str] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)
    reason: str = ""
    message_ids: list[int] = field(default_factory=list)

    @property
    def expected(self) -> str:
        return self.expect.get("reply", "auto")

    @property
    def correct(self) -> bool:
        return not self.problems

    @property
    def wrong(self) -> bool:
        return any(p.startswith("WRONG") for p in self.problems)


def _product_ids(session) -> dict[str, int]:
    return dict(session.execute(select(Product.name, Product.id)).all())


def _item(names: dict[str, int], line: str) -> cart.WantedItem:
    """"Sauvage Eau de Parfum 10ml" / "... full" / "... 5ml x2"."""
    m = re.fullmatch(r"(.+?) (\d+ml|full)(?: x(\d+))?", line.strip())
    if not m or m.group(1) not in names:
        raise ValueError(f"setup item {line!r}: use '<exact product name> <N>ml|full [xN]'")
    full = m.group(2) == "full"
    return cart.WantedItem(names[m.group(1)], None if full else int(m.group(2)[:-2]), full, int(m.group(3) or 1))


STATES = ("browsing", "cart", "confirmed", "waiting_payment", "photo_received", "paid", "packed", "sent_out",
          "delivered")


class Chat:
    """One simulated customer."""

    def __init__(self, number: int):
        self.user = str(FIRST_ID + number)
        self.n = 0
        self.customer_id: int | None = None
        self.phones_given: list[str] = []

    def setup(self, spec: dict | None) -> None:
        spec = spec or {}
        now = datetime.now(UTC)
        age = timedelta(minutes=spec.get("age_min", 30))
        state = spec.get("state", "new")
        with SessionLocal.begin() as s:
            saved = spec.get("saved", state in STATES[2:])
            customer = Customer(channel="telegram", external_user_id=self.user, display_name="Sim",
                                is_tester=bool(spec.get("tester")),
                                address=spec.get("address", "အမှတ် 12, ဗိုလ်ချုပ်လမ်း, လှိုင်မြို့နယ်") if saved else None,
                                phone=spec.get("phone", "09400000001") if saved else None)
            s.add(customer)
            s.flush()
            self.customer_id = customer.id
            if customer.phone:
                cart.set_customer_phones(s, customer, [(customer.phone, None)])
            if state == "new":
                return
            customer.auto_resumed_at = now - timedelta(minutes=1)  # "our last message" is not a hand reply
            s.add(Message(channel="telegram", external_chat_id=self.user, external_message_id="old-in",
                          customer_id=customer.id, raw_text="hi", received_at=now - age - timedelta(minutes=5),
                          direction="in"))
            s.add(Message(channel="telegram", external_chat_id=self.user, external_message_id="old-out",
                          customer_id=customer.id, raw_text="(our last message)", received_at=now - age,
                          direction="out"))
            if state == "browsing":
                return
            names = _product_ids(s)
            order = cart.open_cart(s, customer.id, create=True)
            cart.add_items(s, order, [_item(names, line) for line in spec.get("items", [])], None)
            order.created_at = order.list_sent_at = now - age
            if state == "cart":
                return
            cart.confirm(s, order)
            order.phones, order.address = [customer.phone or "09400000001"], customer.address
            if state == "confirmed":
                return
            order.status, order.payment_info_sent_at = "waiting_payment", now - age
            cart.touch(s, order)
            if state == "waiting_payment":
                return
            shot = Message(channel="telegram", external_chat_id=self.user, external_message_id="old-shot",
                           customer_id=customer.id, raw_text="", received_at=now - age + timedelta(minutes=1),
                           kind="photo")
            s.add(shot)
            s.flush()
            s.add(PaymentCheck(order_id=order.id, message_id=shot.id,
                               decision="pending" if state == "photo_received" else "approved"))
            order.status = "photo_received"
            if state == "photo_received":
                return
            order.order_no = s.execute(text("SELECT nextval('order_no_seq')")).scalar()
            order.status, order.paid_at = "paid", now - age + timedelta(minutes=2)
            for later in ("packed", "sent_out", "delivered"):
                if STATES.index(state) >= STATES.index(later):
                    order.status = later
                    setattr(order, f"{later}_at", now - age + timedelta(minutes=3))

    def travel(self, gap: timedelta) -> None:
        """`gap` passes: every time of this customer moves into the past."""
        with SessionLocal.begin() as s:
            cols = s.execute(text(
                "SELECT c.table_name, c.column_name FROM information_schema.columns c "
                "WHERE c.table_schema = 'public' AND c.data_type = 'timestamp with time zone'")).all()
            keys = {r[0]: r[1] for r in s.execute(text(
                "SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public' "
                "AND column_name IN ('customer_id', 'order_id', 'message_id')"
                " ORDER BY CASE column_name WHEN 'customer_id' THEN 0 WHEN 'order_id' THEN 1 ELSE 2 END DESC"))}
            where = {"customer_id": "customer_id = :c",
                     "order_id": "order_id IN (SELECT id FROM orders WHERE customer_id = :c)",
                     "message_id": "message_id IN (SELECT id FROM messages WHERE customer_id = :c)"}
            by_table: dict[str, list[str]] = {}
            for table, column in cols:
                by_table.setdefault(table, []).append(column)
            for table, columns in by_table.items():
                cond = "id = :c" if table == "customers" else where.get(keys.get(table, ""))
                if cond is None:
                    continue
                sets = ", ".join(f'"{c}" = "{c}" - :g' for c in columns)
                s.execute(text(f'UPDATE "{table}" SET {sets} WHERE {cond}'), {"c": self.customer_id, "g": gap})
            s.execute(text("UPDATE audit_log SET created_at = created_at - :g WHERE (details->>'customer_id')::int = :c "
                           "OR (details->>'message_id')::int IN (SELECT id FROM messages WHERE customer_id = :c)"),
                      {"c": self.customer_id, "g": gap})

    def say(self, body: str, kind: str = "text") -> int:
        self.n += 1
        ext = f"sim-{self.n}"
        self.phones_given += [re.sub(r"\D", "", p) for p in PHONE.findall(body)]
        with SessionLocal.begin() as s:
            save_message(s, ChatMessage(self.user, ext, self.user, None, "Sim Customer", body,
                                        datetime.now(UTC), direction="in", kind=kind,
                                        media_size=1234 if kind == "photo" else None,
                                        media_mime="image/jpeg" if kind == "photo" else None))
            row = s.scalar(select(Message).where(Message.external_chat_id == self.user,
                                                 Message.external_message_id == ext))
            if self.customer_id is None:
                self.customer_id = row.customer_id
            return row.id


class FakeTelegram:
    def __init__(self):
        self.sent: list[tuple[str, str]] = []

    def is_connected(self):
        return True

    async def get_input_entity(self, peer):
        return peer

    async def send_message(self, entity, message, link_preview):
        from telethon.tl import types

        self.sent.append((str(entity.user_id), message))
        return types.Message(id=800000 + len(self.sent), peer_id=entity, date=datetime.now(UTC), message=message,
                             out=True)


def _deliver(fake: FakeTelegram) -> None:
    with SessionLocal.begin() as s:
        s.execute(text("UPDATE outbox SET send_after = now() - interval '1 second' WHERE status = 'queued'"))
    while asyncio.run(sender.send_next(fake, sender.RateLimiter())):
        pass


def _work(at: datetime) -> None:
    """One pass of the parser worker loop (app/parser/worker.py main), at time `at`."""
    while worker.run_batch():
        pass
    worker.scan_payments()
    ai_service.run_once(at)
    auto.run_once(at)


def run_turn(chat: Chat, turn: Turn, fake: FakeTelegram, kind: str) -> None:
    with SessionLocal() as s:
        before = s.scalar(text("SELECT coalesce(max(id), 0) FROM outbox"))
    for body in turn.said:
        turn.message_ids.append(chat.say(body if kind == "text" else "", kind))
    now = datetime.now(UTC)
    _work(now + timedelta(seconds=2))
    _deliver(fake)
    _work(now + timedelta(seconds=4))  # a reply that waited for the first one to go out
    _deliver(fake)
    with SessionLocal() as s:
        boxes = s.execute(text("SELECT reply_kind, text FROM outbox WHERE customer_id = :c AND id > :b "
                               "AND status = 'sent' ORDER BY id"), {"c": chat.customer_id, "b": before}).all()
    if not boxes:  # nothing automatic: the silence watchdog
        holding.run_once(now + holding.WAIT + timedelta(seconds=1))
        _deliver(fake)
        with SessionLocal() as s:
            boxes = s.execute(text("SELECT reply_kind, text FROM outbox WHERE customer_id = :c AND id > :b "
                                   "AND status = 'sent' ORDER BY id"), {"c": chat.customer_id, "b": before}).all()
    turn.replies = [b.text for b in boxes]
    kinds = {b.reply_kind for b in boxes}
    turn.got = "auto" if kinds - {"hold", "holding"} else ("person" if kinds else "none")
    with SessionLocal() as s:
        reasons = s.execute(text(
            "SELECT m.id, r.reason, r.status, p.intent, a.decision, a.error FROM messages m "
            "LEFT JOIN auto_runs r ON r.message_id = m.id "
            "LEFT JOIN parse_results p ON p.message_id = m.id AND p.is_current "
            "LEFT JOIN ai_calls a ON a.message_id = m.id WHERE m.id = ANY(:ids) ORDER BY m.id"),
            {"ids": turn.message_ids}).all()
    if turn.got != "auto":
        r = reasons[-1] if reasons else None
        turn.reason = (f"{r.reason}" if r and r.reason else "waiting (no auto decision)") + \
            (f" | intent {r.intent}" if r else "") + (f" | AI {r.decision}" if r and r.decision else "") + \
            (f" ({r.error[:40]})" if r and r.error else "")


