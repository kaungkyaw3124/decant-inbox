def _amounts(textval: str) -> set[int]:
    return {int(n.replace(",", "")) for n in NUMBER.findall(textval)}


def _allowed_numbers(s, chat: Chat, said: list[str]) -> set[int]:
    allowed = set(range(0, 21))
    for row in s.execute(select(ProductPrice.price_mmk, ProductPrice.size_ml)):
        allowed |= {row.price_mmk or 0, row.size_ml or 0}
    allowed |= {p.full_size_ml for p in s.scalars(select(Product)) if p.full_size_ml}
    for o in s.scalars(select(Order).where(Order.customer_id == chat.customer_id)):
        allowed |= {cart.view(s, o).total, o.order_no or 0, o.total_mmk or 0}
        allowed |= {i.unit_price_mmk * (i.quantity or 1) for i in s.scalars(select(OrderItem).where(
            OrderItem.order_id == o.id)) if i.unit_price_mmk}
    for t in replies.load(s).values():
        allowed |= _amounts(t)
    for t in s.scalars(text("SELECT answer FROM faq_entries")):
        allowed |= _amounts(t)
    for t in s.scalars(text("SELECT account_number FROM payment_methods")):
        allowed |= _amounts(t)
    for t in s.scalars(text("SELECT value::text FROM app_settings")):
        allowed |= _amounts(t)
    for t in said:
        allowed |= _amounts(t)
    return allowed


def _cart_lines(s, chat: Chat) -> list[str] | None:
    order = cart.open_cart(s, chat.customer_id)
    if order is None:
        return []
    names = dict(s.execute(select(Product.id, Product.name)).all())
    lines = []
    for i in s.scalars(select(OrderItem).where(OrderItem.order_id == order.id, OrderItem.removed_at.is_(None))
                       .order_by(OrderItem.id)):
        size = "full" if i.is_full_bottle else f"{i.size_ml}ml"
        lines.append(f"{names.get(i.product_id, '?' + (i.unknown_text or ''))} {size} x{i.quantity or 1}")
    return lines


def judge(chat: Chat, turn: Turn, said_so_far: list[str]) -> None:
    e, reply = turn.expect, "\n".join(turn.replies)
    p = turn.problems
    want = turn.expected
    if want == "person":
        if turn.got == "auto":
            p.append("WRONG: answered automatically, a person must handle this")
        elif turn.got == "none":
            p.append("SILENT: no holding reply")
    elif want == "none":
        if turn.got != "none":
            p.append(f"not expected to reply, got {turn.got}")
    elif want == "any_auto":
        if turn.got == "person":
            p.append("needs a person (expected automatic or nothing)")
    else:
        if turn.got == "none":
            p.append("SILENT: no reply at all")
        elif turn.got == "person":
            p.append(f"needs a person: {turn.reason}")
    for piece in e.get("contains", []):
        if piece not in reply:
            p.append(f"missing {piece!r}")
    if e.get("any_of") and not any(x in reply for x in e["any_of"]):
        p.append(f"none of {e['any_of']!r}")
    for piece in e.get("not_contains", []):
        if piece in reply:
            p.append(f"WRONG: says {piece!r}")
    with SessionLocal() as s:
        if "cart" in e:
            got = _cart_lines(s, chat)
            if sorted(got) != sorted(e["cart"]):
                p.append(f"WRONG cart: {got} (expected {e['cart']})")
        newest = s.scalar(select(Order).where(Order.customer_id == chat.customer_id).order_by(Order.id.desc()).limit(1))
        if "status" in e and (newest is None or newest.status != e["status"]):
            p.append(f"status {newest.status if newest else None} (expected {e['status']})")
        if "phone" in e and (newest is None or e["phone"] not in (newest.phones or [])):
            p.append(f"WRONG phone: {newest.phones if newest else None}")
        parts = (newest.address_parts or {}) if newest else {}
        for key in ("city", "township"):
            if key in e and e[key].lower() not in str(parts.get(key) or "").lower():
                p.append(f"WRONG {key}: {parts.get(key)!r} (expected {e[key]!r})")
        if not reply:
            return
        # strict: numbers, products, phones, Order IDs
        bad = sorted(_amounts(reply) - _allowed_numbers(s, chat, said_so_far))
        if bad:
            p.append(f"WRONG number(s) {bad}")
        names = sorted(_product_ids(s), key=len, reverse=True)
        allowed = set(e.get("products", [])) | {line.rsplit(" ", 2)[0] for line in e.get("cart", [])}
        allowed |= set(s.scalars(text(  # what the customer named in this turn (rules or AI reading)
            "SELECT p.name FROM parse_items i JOIN parse_results r ON r.id = i.parse_result_id AND r.is_current "
            "JOIN products p ON p.id = coalesce(i.product_id, i.candidate_product_id) WHERE r.message_id = ANY(:m)"),
            {"m": turn.message_ids}))
        if newest is not None:
            allowed |= {n for n in names if n in "\n".join(_cart_lines(s, chat) or [])}
            for o in s.scalars(select(Order).where(Order.customer_id == chat.customer_id)):
                allowed |= {n for (n,) in s.execute(text(
                    "SELECT p.name FROM order_items i JOIN products p ON p.id = i.product_id WHERE i.order_id = :o"),
                    {"o": o.id})}
        rest = reply
        choice = bool(re.search(r"(?m)^\s*\d+[.)]", reply))
        for name in names:
            if name in rest:
                rest = rest.replace(name, "")
                if name not in allowed and not choice:
                    p.append(f"WRONG product named: {name}")
        given = chat.phones_given
        for phone in {re.sub(r"\D", "", x) for x in PHONE.findall(reply)}:
            ok = phone == given[-1] if given else phone in {re.sub(r"\D", "", x) for x in [
                *(s.scalars(text("SELECT phone FROM customer_phones WHERE customer_id = :c"),
                            {"c": chat.customer_id})), *s.scalars(text("SELECT account_number FROM payment_methods"))]}
            if not ok and phone not in {re.sub(r"\D", "", x) for x in s.scalars(text(
                    "SELECT account_number FROM payment_methods"))}:
                p.append(f"WRONG phone shown {phone}")
        ours = {str(n) for n in s.scalars(text("SELECT order_no FROM orders WHERE customer_id = :c AND order_no "
                                                "IS NOT NULL"), {"c": chat.customer_id})}
        for no in ORDER_NO.findall(reply):
            if no not in ours and not any(no in t for t in said_so_far):
                p.append(f"WRONG Order ID #{no}")
        if "complaint" in e.get("tags", []) or e.get("complaint"):
            if PROMISE.search(reply):
                p.append("WRONG: promises a refund / replacement")


