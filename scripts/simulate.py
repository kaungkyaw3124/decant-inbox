def finish(chat: Chat) -> None:
    """Scenario over: its open messages no longer wait (other scenarios must not see them)."""
    with SessionLocal.begin() as s:
        s.execute(text("INSERT INTO auto_runs (message_id, status, reason) SELECT id, 'skipped', 'sim: scenario over' "
                       "FROM messages m WHERE customer_id = :c AND direction = 'in' "
                       "AND NOT EXISTS (SELECT 1 FROM auto_runs r WHERE r.message_id = m.id)"), {"c": chat.customer_id})
        s.execute(text("UPDATE outbox SET status = 'cancelled' WHERE customer_id = :c AND status = 'queued'"),
                  {"c": chat.customer_id})


def run_scenario(number: int, sc: dict, fake: FakeTelegram) -> list[Turn]:
    chat = Chat(number)
    chat.setup(sc.get("setup"))
    turns, said = [], []
    for i, t in enumerate(sc["turns"]):
        if t.get("gap_min"):
            chat.travel(timedelta(minutes=t["gap_min"]))
        bodies = t["say"] if isinstance(t.get("say"), list) else [t.get("say", "")]
        kind = "photo" if t.get("photo") else "other" if t.get("voice") or t.get("sticker") else "text"
        turn = Turn(i, bodies, {**(t.get("expect") or {}), "tags": sc.get("tags", [])})
        said += bodies
        run_turn(chat, turn, fake, kind)
        judge(chat, turn, said)
        turns.append(turn)
    finish(chat)
    return turns


@dataclass
class Score:
    turns: int = 0
    correct: int = 0
    wrong: int = 0
    silent: int = 0
    person: int = 0
    reasons: Counter = field(default_factory=Counter)
    failed: list = field(default_factory=list)

    @property
    def automatic(self) -> float:
        return self.correct / self.turns if self.turns else 0.0

    @property
    def met(self) -> bool:
        return self.automatic >= GOAL_AUTOMATIC and self.wrong <= GOAL_WRONG and self.silent <= GOAL_SILENT

    def line(self) -> str:
        top = "; ".join(f"{r} ×{n}" for r, n in self.reasons.most_common(3))
        return (f"automatic {self.automatic:.1%} ({self.correct}/{self.turns}), wrong {self.wrong}, silent "
                f"{self.silent}, needs-person {self.person / max(self.turns, 1):.1%}; top reasons: {top or '-'}")


def score(results: list[tuple[dict, list[Turn]]]) -> Score:
    sc = Score()
    for scenario, turns in results:
        for t in turns:
            sc.turns += 1
            sc.correct += t.correct
            sc.wrong += t.wrong
            sc.silent += any(x.startswith("SILENT") for x in t.problems)
            sc.person += t.got == "person"
            if not t.correct:
                first = t.problems[0]
                key = "needs a person: " + t.reason.split(" | ")[0] if first.startswith("needs a person") else first
                sc.reasons[re.sub(r"[\d,]{3,}|'[^']*'|\[[^\]]*\]", "…", key)[:90]] += 1
                sc.failed.append((scenario["id"], t))
    return sc


def run(scenarios: list[dict], provider: providers.Provider | None, verbose: bool = False) -> Score:
    providers.use(provider)
    ai_service._not_needed.clear()
    fake = FakeTelegram()
    results = []
    try:
        for number, sc in enumerate(scenarios, start=1):
            turns = run_scenario(number, sc, fake)
            results.append((sc, turns))
            if verbose:
                for t in turns:
                    mark = "✅" if t.correct else ("❌" if t.wrong else "🟡")
                    print(f"{mark} {sc['id']}#{t.index} got {t.got}: {'; '.join(t.problems)[:200]}")
                    if not t.correct:
                        for r in t.replies:
                            print("     > " + r.replace("\n", "\n     > "))
    finally:
        providers.use(None)
    return score(results)


def fresh_database() -> None:
    from alembic import command
    from alembic.config import Config
    from sqlalchemy import create_engine

    from app.core.config import get_settings
    from app.core.db import engine

    name = get_settings().db_name
    assert name.endswith("_sim"), "the simulator only ever drops its own database"
    admin = create_engine(get_settings().database_url.set(database="postgres"), isolation_level="AUTOCOMMIT")
    engine.dispose()
    with admin.connect() as c:
        c.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        c.execute(text(f'CREATE DATABASE "{name}"'))
        c.execute(text(f'ALTER DATABASE "{name}" SET synchronous_commit = off'))
    admin.dispose()
    command.upgrade(Config(str(BASE_DIR / "alembic.ini")), "head")


