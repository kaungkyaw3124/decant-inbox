"""Writes app/web/static/icons.css: only the Bootstrap Icons the templates use (the full CSS is 87 KB and would
break the 400 KB page budget, docs/SPEC-v4.15-ui-bootstrap.md). Run after adding an icon to a template:
  .venv/bin/python -m scripts.vendor_icons"""
import json
import re
from pathlib import Path

WEB = Path(__file__).resolve().parent.parent / "app" / "web"
VENDOR = "/static/vendor/bootstrap-icons-1.13.1"


def main() -> None:
    codes = json.loads((WEB / "static/vendor/bootstrap-icons-1.13.1/bootstrap-icons.json").read_text())
    used = sorted({name for path in (WEB / "templates").glob("*.html")
                   for name in re.findall(r"\bbi-([a-z0-9-]+)", path.read_text()) if name in codes})
    css = [f'@font-face{{font-display:block;font-family:"bootstrap-icons";src:url("{VENDOR}/bootstrap-icons.woff2") format("woff2")}}',
           '.bi::before,[class^="bi-"]::before,[class*=" bi-"]::before{display:inline-block;font-family:bootstrap-icons!important;'
           'font-style:normal;font-weight:normal!important;font-variant:normal;text-transform:none;line-height:1;'
           'vertical-align:-.125em;-webkit-font-smoothing:antialiased}']
    css += [f'.bi-{name}::before{{content:"\\{codes[name]:x}"}}' for name in used]
    (WEB / "static/icons.css").write_text("/* generated by scripts/vendor_icons.py (Bootstrap Icons 1.13.1, MIT) */\n"
                                          + "\n".join(css) + "\n")
    print(f"icons.css: {len(used)} icons")


if __name__ == "__main__":
    main()
